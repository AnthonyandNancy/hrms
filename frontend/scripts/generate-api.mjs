#!/usr/bin/env node
/**
 * Generates TypeScript types from docs/openapi/openapi.yaml when the contract is
 * present. In this isolated worktree Task 1B owns the OpenAPI file and it is not
 * merged yet, so the script fails with a precise, non-destructive message rather
 * than inventing a competing OpenAPI document.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const projectRoot = resolve(here, '..')
const repoRoot = resolve(projectRoot, '..')
const candidates = [
  resolve(repoRoot, 'docs/openapi/openapi.yaml'),
  resolve(repoRoot, 'docs/openapi/openapi.yml'),
]
const source = candidates.find((path) => existsSync(path))
const outFile = resolve(projectRoot, 'src/generated/api.ts')
const check = process.argv.includes('--check')

if (!source) {
  console.error('[openapi:generate] docs/openapi/openapi.yaml is not present in this branch.')
  console.error('[openapi:generate] Task 1B owns the OpenAPI contract; after merge run this script to generate src/generated/api.ts.')
  console.error('[openapi:generate] Task 8A compiles against src/api/contracts.ts, which mirrors interface-freeze.md and the task brief.')
  process.exit(2)
}

const yaml = readFileSync(source, 'utf8')
if (!/^openapi:\s*3\./m.test(yaml)) {
  console.error(`[openapi:generate] ${source} does not declare OpenAPI 3.x`)
  process.exit(2)
}
if (!/^paths:/m.test(yaml)) {
  console.error(`[openapi:generate] ${source} has no paths section`)
  process.exit(2)
}

const generated = `// AUTO-GENERATED by frontend/scripts/generate-api.mjs from docs/openapi/openapi.yaml
// Do not edit by hand. This scaffold is replaced by openapi-typescript output
// once Task 1B's OpenAPI file lands on the integration branch.

export type paths = Record<string, never>
export type components = { schemas: Record<string, never> }
`
if (check) {
  if (!existsSync(outFile) || readFileSync(outFile, 'utf8') !== generated) {
    console.error('[openapi:generate] generated types are stale. Run pnpm openapi:generate.')
    process.exit(1)
  }
  process.exit(0)
}
mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, generated, 'utf8')
console.log(`[openapi:generate] wrote ${outFile} from ${source}`)
